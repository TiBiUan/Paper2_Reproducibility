% Main Practical Utility quantities
MetricNames = { ...
    'StructuralMismatch', ...
    'Error_Functional', ...
    'Rel_DeltaC', ...
    'Error_FC'};

MetricLabels = { ...
    'Structural mismatch', ...
    'Functional error', ...
    'Second-order moment error', ...
    'FC error'};

% Filtering conditions
Filters = ["Low","High"];

% Colors
ColLow  = [0.45 0.75 0.73];
ColHigh = [0.55 0.48 0.75];

% Subject-level values, averaged across repeated outer-fold occurrences
T = PracticalUtilitySubjectMeans;

% Reference population-connectome construction
T = T( ...
    T.Topology == "AllEdges" & ...
    T.Weights == "AllValues",:);

% Horizontal positions
xCenter = 1:numel(MetricNames);
dx = 0.18;

figure;
hold on;

for m = 1:numel(MetricNames)

    % Current metric
    Tm = T(T.Metric == MetricNames{m},:);

    % Low- and high-pass subject-level observations
    yLow = Tm.MeanAcrossOuter(Tm.Filter == Filters(1));
    yHigh = Tm.MeanAcrossOuter(Tm.Filter == Filters(2));

    % Removes missing observations
    yLow = yLow(isfinite(yLow));
    yHigh = yHigh(isfinite(yHigh));

    % Horizontal positions
    xLow = xCenter(m) - dx;
    xHigh = xCenter(m) + dx;

    % Individual subject observations
    swarmchart( ...
        repmat(xLow,size(yLow)), ...
        yLow, ...
        8, ...
        ColLow, ...
        'filled', ...
        'MarkerFaceAlpha',0.20, ...
        'MarkerEdgeAlpha',0.20, ...
        'XJitterWidth',0.22);

    swarmchart( ...
        repmat(xHigh,size(yHigh)), ...
        yHigh, ...
        8, ...
        ColHigh, ...
        'filled', ...
        'MarkerFaceAlpha',0.20, ...
        'MarkerEdgeAlpha',0.20, ...
        'XJitterWidth',0.22);

    % Boxplots
    boxchart( ...
        repmat(xLow,size(yLow)), ...
        yLow, ...
        'BoxFaceColor','k', ...
        'BoxWidth',0.10, ...
        'MarkerStyle','none');

    boxchart( ...
        repmat(xHigh,size(yHigh)), ...
        yHigh, ...
        'BoxFaceColor','k', ...
        'BoxWidth',0.10, ...
        'MarkerStyle','none');

end

% Axes
xlim([0.5 numel(MetricNames)+0.5]);

xticks(xCenter);
xticklabels(MetricLabels);

ylabel('Error / mismatch');

box off;

set(gca, ...
    'TickDir','out', ...
    'FontSize',12);

% Legend
hLow = scatter( ...
    nan,nan,30, ...
    'MarkerFaceColor',ColLow, ...
    'MarkerEdgeColor','none');

hHigh = scatter( ...
    nan,nan,30, ...
    'MarkerFaceColor',ColHigh, ...
    'MarkerEdgeColor','none');

legend( ...
    [hLow hHigh], ...
    {'Low-pass','High-pass'}, ...
    'Location','best', ...
    'Box','off');


