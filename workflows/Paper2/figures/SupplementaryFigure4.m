%% Supplementary Figure 4B - Behavioral prediction

% Feature pairs displayed in the Supplementary Figure
FeaturePairs = { ...
    {'FC','Cx'}, ...
    {'DC_Low','DC_High'}, ...
    {'EC_Low','EC_High'}, ...
    {'CT_Low','CT_High'}, ...
    {'FC_Pop_Low','FC_Pop_High'}, ...
    {'FC_Ind_Low','FC_Ind_High'}, ...
    {'Delta_FC_Low','Delta_FC_High'}, ...
    {'Error_FC_Low','Error_FC_High'}};

PairLabels = { ...
    'FC / Cx', ...
    'Difference in 2nd-order moment', ...
    'Error-term', ...
    'Cross-term', ...
    'FC population', ...
    'FC individual', ...
    'Difference in FC', ...
    'FC error'};


figure;
hold on;

PairSpacing = 1.5;
WithinPairSpacing = 0.32;


for p = 1:numel(FeaturePairs)

    % Finds feature rows by name rather than historical row position
    id1 = find(strcmp(FeatureNames,FeaturePairs{p}{1}));
    id2 = find(strcmp(FeatureNames,FeaturePairs{p}{2}));

    assert(numel(id1) == 1 && numel(id2) == 1, ...
        'Prediction feature not found uniquely.');

    % Horizontal positions
    x1 = 1 + (p-1)*PairSpacing;
    x2 = x1 + WithinPairSpacing;

    % Fold-wise prediction performance
    y1 = R2_Distribution(id1,:);
    y2 = R2_Distribution(id2,:);

    % Paired outer folds
    for f = 1:size(R2_Distribution,2)

        plot( ...
            [x1 x2], ...
            [y1(f) y2(f)], ...
            '-', ...
            'Color',[0.7 0.7 0.7], ...
            'LineWidth',0.5);

    end


    % ---------------------------------------------------------------------
    % Display colors
    % ---------------------------------------------------------------------

    if p == 1

        % FC and unfiltered second-order moment
        c1 = [0 0 0];
        c2 = [0 0 0];

    else

        % Low- and high-pass filtering
        c1 = cLow;
        c2 = cHigh;

    end


    % Fold observations
    scatter( ...
        repmat(x1,size(y1)), ...
        y1, ...
        20,c1, ...
        'filled');

    scatter( ...
        repmat(x2,size(y2)), ...
        y2, ...
        20,c2, ...
        'filled');


    % Median across folds
    plot( ...
        x1,median(y1,'omitnan'), ...
        '_k', ...
        'MarkerSize',16, ...
        'LineWidth',2);

    plot( ...
        x2,median(y2,'omitnan'), ...
        '_k', ...
        'MarkerSize',16, ...
        'LineWidth',2);

end


% Pair centers
PairCenters = ...
    1 + (0:numel(FeaturePairs)-1)*PairSpacing + ...
    WithinPairSpacing/2;

xticks(PairCenters);
xticklabels(PairLabels);

ylabel('Prediction R^2');

yline(0,'-','Color',[0.75 0.75 0.75]);

box off;

set(gca, ...
