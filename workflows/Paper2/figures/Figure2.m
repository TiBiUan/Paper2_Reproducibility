load(fullfile(ResultsDir,'Robustness_Results.mat'),'Robustness');
load(fullfile(ResultsDir,'Robustness_Results.mat'),'RobustnessStats');
load(fullfile(ResultsDir,'Robustness_Results.mat'),'RobustnessDescriptives');



%% Color maps

% Heat maps
CM_Reds = cbrewer2('seq','Reds',1000,'linear');
CM_OrRd = cbrewer2('seq','OrRd',1000,'linear');

% Harmonic similarity convergence curves
CM_Qual = cbrewer2('qual','Paired',12);

% Required projection window convergence curves
CM_PERW = cbrewer2('seq','OrRd',9);
CM_PERW = CM_PERW([6,4],:);

% Laplacian reconstruction error
CM_LRE = CM_Reds(end,:);



%% Figure 2A - Harmonic-wise Robustness

% Reference construction
Topology = 'AllEdges';
Weights = 'AllValues';

% Population sample sizes
NSamples = [5,10,20,30,40,50,75,100,125,150,175,200,250,300,350];

% Number of outer and Monte Carlo realizations
NumOuter = numel(Robustness.Outer);
NumMC = numel(Robustness.Outer(1).MonteCarlo);

% Number of harmonics
NumHarmonics = numel( ...
    Robustness.Outer(1).MonteCarlo(1).SampleSize(1). ...
    (Topology).(Weights).HarmonicSimilarity.Match);

% Stores harmonic-wise quantities across all realizations
HWSM = nan(NumHarmonics,numel(NSamples),NumOuter,NumMC);
PERW = nan(NumHarmonics,numel(NSamples),NumOuter,NumMC);

% Collects harmonic-wise quantities
for o = 1:NumOuter

    for mc = 1:NumMC

        for ns = 1:numel(NSamples)

            % Matched harmonic-wise similarity
            HWSM(:,ns,o,mc) = ...
                Robustness.Outer(o).MonteCarlo(mc).SampleSize(ns). ...
                (Topology).(Weights).HarmonicSimilarity.Match(:);

            % Required projection windows
            PERW(:,ns,o,mc) = ...
                Robustness.Outer(o).MonteCarlo(mc).SampleSize(ns). ...
                (Topology).(Weights).RequiredProjectionWindow(:);

        end
    end
end

% Average across all {Outer,MC} realizations
HeatMap_HWSM = mean(HWSM,[3 4],'omitnan');
HeatMap_PERW = mean(PERW,[3 4],'omitnan');

% -------------------------------------------------------------------------
% Matched harmonic similarity
% -------------------------------------------------------------------------

figure;

imagesc(NSamples,1:NumHarmonics,HeatMap_HWSM);

colormap(CM_Reds);
clim([0 1]);

xlabel('Population sample size');
ylabel('Harmonic index');

set(gca, ...
    'YDir','normal', ...
    'TickDir','out', ...
    'Box','off');


% -------------------------------------------------------------------------
% Required projection windows
% -------------------------------------------------------------------------

figure;

imagesc(NSamples,1:NumHarmonics,HeatMap_PERW);

colormap(flipud(CM_OrRd));
clim([0 30]);

xlabel('Population sample size');
ylabel('Harmonic index');

set(gca, ...
    'YDir','normal', ...
    'TickDir','out', ...
    'Box','off');


%% Figure 2B - Robustness convergence

% Reference construction
TStats = RobustnessStats( ...
    RobustnessStats.Topology == "AllEdges" & ...
    RobustnessStats.Weights == "AllValues",:);

TDescr = RobustnessDescriptives( ...
    RobustnessDescriptives.Topology == "AllEdges" & ...
    RobustnessDescriptives.Weights == "AllValues",:);


%% Matched harmonic similarity

Metrics = { ...
    'Median_HarmSim_Match', ...
    'P05_HarmSim_Match'};

Colors = [ ...
    CM_Qual(6,:); ...
    CM_Qual(5,:)];

figure;
hold on;


for m = 1:numel(Metrics)

    % Current metric
    Metric = Metrics{m};


    % ---------------------------------------------------------------------
    % Individual {Outer,MC} realization trajectories
    % ---------------------------------------------------------------------

    for o = unique(TStats.Outer)'

        MCValues = unique(TStats.MC(TStats.Outer == o));

        for mc = MCValues'

            idx = ...
                TStats.Outer == o & ...
                TStats.MC == mc;

            Ttmp = sortrows(TStats(idx,:),'N');

            plot( ...
                Ttmp.N, ...
                Ttmp.(Metric), ...
                'LineWidth',0.25, ...
                'Color',[0.6 0.6 0.6]);

        end
    end


    % ---------------------------------------------------------------------
    % Across-realization descriptives
    % ---------------------------------------------------------------------

    TD = TDescr(TDescr.Metric == Metric,:);
    TD = sortrows(TD,'N');

    % 2.5th-97.5th percentile interval
    fill( ...
        [TD.N' fliplr(TD.N')], ...
        [TD.P025' fliplr(TD.P975')], ...
        Colors(m,:), ...
        'EdgeColor','none', ...
        'FaceAlpha',0.5);

    % Mean across realizations
    plot( ...
        TD.N, ...
        TD.Mean, ...
        'LineWidth',2, ...
        'Color',Colors(m,:), ...
        'Marker','o', ...
        'MarkerFaceColor',Colors(m,:), ...
        'MarkerSize',6, ...
        'MarkerEdgeColor','k');

end


xlim([5 350]);

xlabel('Population sample size');
ylabel('Matched harmonic similarity');

box off;

set(gca, ...
    'TickDir','out', ...
    'FontSize',12);


