%% Figure 2 - Robustness
%
% Visualizes Robustness for the reference AllEdges/AllValues construction.
%
% Figure 2A:
%   Harmonic-wise heat maps of matched harmonic similarity and required
%   projection windows across population sample sizes. Values are averaged
%   across all {Outer,MC} realizations.
%
% Figure 2B:
%   Convergence curves for:
%       - Median matched harmonic similarity
%       - 5th-percentile matched harmonic similarity
%       - Median required projection windows
%       - 95th-percentile required projection windows
%       - Laplacian reconstruction error
%
% All analytical quantities are generated by Run_Robustness.m



