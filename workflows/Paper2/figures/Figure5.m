%% Figure 5 - Relationships across pillars
%
% Generates Figure 5 from previously computed cross-pillar results.
%
% Figure 5A:
%   Relationship between Robustness and Representativeness across
%   population realizations and sample sizes.
%
% Figure 5B:
%   Subject-level relationships between Representativeness and Practical
%   Utility for low- and high-pass graph filtering.
%
% Figure 5C:
%   Normalized observed convergence of Robustness, Representativeness and
%   Practical Utility quantities across population sample sizes.
%
% This script performs visualization only. All analytical quantities are
% generated by Run_CrossPillarRelationships.m



%% Loading the required data

RepositoryDir = '/Users/bolton/Desktop/Paper2_Reproducibility';
DataDir = '/Users/bolton/Desktop/Paper2_Data';
ResultsDir = fullfile(RepositoryDir,'results');

addpath(genpath(fullfile(RepositoryDir,'src')));
addpath(genpath(fullfile(RepositoryDir,'external')));

load(fullfile(ResultsDir,'CrossPillarAnalysis_Results.mat'));



%% Definitions

AlphaVal = 0.3;

% Sample-size color map
NSamples = unique(RobustnessRepresentativenessStats.N);
CM = cbrewer2('div','PuOr',numel(NSamples),'linear');

% Representativeness metric colors
CM_Harmo = cbrewer2('div','PiYG',11,'linear');

% Practical Utility colors
CM_PU_Low = cbrewer2('div','BrBG',11,'linear');
CM_PU_High = cbrewer2('div','PRGn',11,'linear');


%% Figure 5A - Robustness versus Representativeness

T = RobustnessRepresentativenessStats;

NSamples = unique(T.N);

figure;
hold on;

for ns = 1:numel(NSamples)

    % Current sample size
    N = NSamples(ns);

    % Corresponding population realizations
    TN = T(T.N == N,:);

    % Current color
    c = CM(ns,:);

    % Matched Robustness and Representativeness observations
    x = TN.Robustness;
    y = TN.MeanRepresentativeness;

    % Individual population realizations
    scatter( ...
        x,y, ...
        8,c, ...
        'filled');

    % Linear trend displayed as a visual guide
    p = polyfit(x,y,1);

    xx = linspace(min(x),max(x),100);
    yy = polyval(p,xx);

    plot( ...
        xx,yy, ...
        'Color',c, ...
        'LineWidth',2);

end

xlabel('Robustness');
ylabel('Mean representativeness');

box off;

set(gca, ...
    'TickDir','out', ...
    'FontSize',12);


%% Figure 5B - Representativeness versus Practical Utility

T = RepresentativenessPracticalUtilityFrequencyComparison;

% Practical Utility quantities
MetricNames = { ...
    'StructuralMismatch', ...
    'Error_Functional', ...
    'Rel_DeltaC', ...
    'Error_FC'};

MetricLabels = { ...
    'Structural mismatch', ...
    'Functional error', ...
    'Second-order moment error', ...
    'FC error'};

% Sample sizes
NSamples = unique(T.N);

% Colors corresponding to sample size
CM = cbrewer2('div','PuOr',numel(NSamples),'linear');

% Horizontal positions
xLow = 1:numel(MetricNames);
xHigh = xLow + 0.30;
xCenter = (xLow+xHigh)/2;

figure;
hold on;


for m = 1:numel(MetricNames)

    % Current Practical Utility quantity
    metric = MetricNames{m};

    % Corresponding correlations
    Tm = T(T.Metric == metric,:);

    % Same process across sample sizes
    for ns = 1:numel(NSamples)

        % Current sample size
        N = NSamples(ns);

        % Corresponding {Outer,MC} realizations
        TN = Tm(Tm.N == N,:);

        % Current color
        c = CM(ns,:);

        % Low- and high-pass Spearman correlations
        yLow = TN.Rho_Low;
        yHigh = TN.Rho_High;

        % Connects matched Low/High observations
        for r = 1:height(TN)

            plot( ...
                [xLow(m) xHigh(m)], ...
                [yLow(r) yHigh(r)], ...
                '-', ...
                'Color',[0.8 0.8 0.8], ...
                'LineWidth',0.5);

        end

        % Low-pass observations
        scatter( ...
            repmat(xLow(m),height(TN),1), ...
            yLow, ...
            12,c, ...
            'filled');

        % High-pass observations
        scatter( ...
            repmat(xHigh(m),height(TN),1), ...
            yHigh, ...
            12,c, ...
            'filled');

    end


    % ---------------------------------------------------------------------
    % Overall descriptive medians
    % ---------------------------------------------------------------------

    plot( ...
        xLow(m), ...
        median(Tm.Rho_Low,'omitnan'), ...
        '_', ...
        'Color','k', ...
        'MarkerSize',16, ...
        'LineWidth',2);

    plot( ...
        xHigh(m), ...
        median(Tm.Rho_High,'omitnan'), ...
        '_', ...
        'Color','k', ...
        'MarkerSize',16, ...
        'LineWidth',2);

end


% -------------------------------------------------------------------------
% Axes
% -------------------------------------------------------------------------

xlim([0.5 numel(MetricNames)+0.8]);

xticks(xCenter);
xticklabels(MetricLabels);

ylabel('Spearman correlation');

yline(0,'--k');

box off;

set(gca, ...
    'TickDir','out', ...
    'FontSize',12);


% -------------------------------------------------------------------------
% Low/High labels
% -------------------------------------------------------------------------

yl = ylim;

for m = 1:numel(MetricNames)

    text( ...
        xLow(m),yl(2), ...
        'Low', ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','bottom');

    text( ...
        xHigh(m),yl(2), ...
        'High', ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','bottom');

end


